-- ============================================================================
-- 2. immutable_unaccent
--
-- Postgres marks unaccent() STABLE, but a GENERATED ... STORED column requires
-- an IMMUTABLE expression. Pinning the dictionary by regdictionary makes the
-- call deterministic, which is what lets us wrap it as IMMUTABLE.
--
-- This MUST be defined before the generated column below, otherwise the
-- ALTER TABLE fails with "generation expression is not immutable".
-- ============================================================================
CREATE OR REPLACE FUNCTION immutable_unaccent(text) RETURNS text AS
$$ SELECT public.unaccent('public.unaccent'::regdictionary, $1) $$
LANGUAGE sql IMMUTABLE PARALLEL SAFE STRICT;

