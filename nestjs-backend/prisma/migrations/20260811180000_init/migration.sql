-- ============================================================================
-- 5. Full-text search column
--
-- Diacritics are folded on the indexed side so a query typed without them
-- ("hop dong") matches text that has them ("hợp đồng"). metadata is folded into
-- the same vector, which is why there is no separate metadata search branch.
--
-- No ivfflat index on embedding_chunks.embedding: the demo corpus is ~13
-- vectors and `lists = 100` would scatter them across mostly-empty lists,
-- so a probe returns arbitrary or empty neighbours. Sequential scan is both
-- faster and correct at this size.
-- ============================================================================
ALTER TABLE "Document"
  ADD COLUMN "search_tsv" tsvector
  GENERATED ALWAYS AS (
    to_tsvector('simple',
      immutable_unaccent(
        coalesce("title", '') || ' ' ||
        coalesce("textContent", '') || ' ' ||
        coalesce("metadata"::text, '')
      ))
  ) STORED;

CREATE INDEX "Document_search_tsv_idx" ON "Document" USING GIN ("search_tsv");
